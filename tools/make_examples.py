#!/usr/bin/env python3
"""Build src/examples.js: small built-in example files shown on BlueMolecule's start screen.

The benzene orbital is computed here from a Hueckel model (Slater 2p_z functions), so it is
illustrative rather than an ab initio result. The other examples are the synthetic test fixtures.
"""
import json
import math
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
FIX = ROOT / 'tests' / 'fixtures'
BOHR = 0.529177210903


def benzene_cube(n=38):
    cc, ch = 1.397, 1.087
    atoms = []
    for k in range(6):
        a = 2 * math.pi * k / 6
        atoms.append((6, cc * math.cos(a), cc * math.sin(a), 0.0))
    for k in range(6):
        a = 2 * math.pi * k / 6
        atoms.append((1, (cc + ch) * math.cos(a), (cc + ch) * math.sin(a), 0.0))
    # Hueckel e1g HOMO (one of the degenerate pair): c_k = cos(2 pi k / 6) / sqrt(3)
    coef = [math.cos(2 * math.pi * k / 6) / math.sqrt(3) for k in range(6)]
    zeta = 1.625
    norm = math.sqrt(zeta ** 5 / math.pi)
    span = 5.2 / BOHR  # half-width in bohr
    origin = np.array([-span, -span, -0.75 * span])
    step = np.array([2 * span / (n - 1), 2 * span / (n - 1), 1.5 * span / (n - 1)])
    xs = origin[0] + step[0] * np.arange(n)
    ys = origin[1] + step[1] * np.arange(n)
    zs = origin[2] + step[2] * np.arange(n)
    X, Y, Zg = np.meshgrid(xs, ys, zs, indexing='ij')
    psi = np.zeros_like(X)
    for c, (_, ax, ay, az) in zip(coef, atoms[:6]):
        dx, dy, dz = X - ax / BOHR, Y - ay / BOHR, Zg - az / BOHR
        r = np.sqrt(dx * dx + dy * dy + dz * dz)
        psi += c * norm * dz * np.exp(-zeta * r)
    lines = ['Benzene pi orbital (Hueckel model, Slater 2pz, illustrative)', 'BlueMolecule example: HOMO-like e1g combination']
    lines.append(f'{len(atoms):5d}{origin[0]:12.6f}{origin[1]:12.6f}{origin[2]:12.6f}')
    lines.append(f'{n:5d}{step[0]:12.6f}{0:12.6f}{0:12.6f}')
    lines.append(f'{n:5d}{0:12.6f}{step[1]:12.6f}{0:12.6f}')
    lines.append(f'{n:5d}{0:12.6f}{0:12.6f}{step[2]:12.6f}')
    for z, x, y, zz in atoms:
        lines.append(f'{z:5d}{float(z):12.6f}{x / BOHR:12.6f}{y / BOHR:12.6f}{zz / BOHR:12.6f}')
    for i in range(n):
        for j in range(n):
            row = psi[i, j, :]
            for s in range(0, n, 6):
                lines.append(''.join(f'{v:13.4E}' for v in row[s:s + 6]))
    return '\n'.join(lines) + '\n'


def main():
    ex = [
        {'id': 'g16-water', 'label': 'Water opt + freq (Gaussian)', 'name': 'water_optfreq_example.log',
         'text': (FIX / 'g16_water_optfreq.log').read_text(), 'note': 'Synthetic Gaussian-format output: optimisation steps, vibrations, IR/Raman'},
        {'id': 'orca-td', 'label': 'Water TD-DFT (ORCA)', 'name': 'water_tddft_example.out',
         'text': (FIX / 'orca5_water_tddft.out').read_text(), 'note': 'Synthetic ORCA-format output: excited states and UV-Vis'},
        {'id': 'benzene-cube', 'label': 'Benzene π orbital (cube)', 'name': 'benzene_pi_example.cube',
         'text': benzene_cube(), 'note': 'Hückel-model orbital on a grid: isosurfaces'},
        {'id': 'cisplatin', 'label': 'Cisplatin (XYZ)', 'name': 'cisplatin_example.xyz',
         'text': (FIX / 'cisplatin.xyz').read_text(), 'note': 'Structure only'},
    ]
    body = json.dumps(ex, ensure_ascii=False).replace('</', '<\\/')
    out = ROOT / 'src' / 'examples.js'
    out.write_text('/* BlueMolecule built-in examples (generated by tools/make_examples.py). */\n'
                   '(function (BM) { BM.examples = ' + body + '; })(window.BM = window.BM || {});\n', encoding='utf-8')
    print(f'wrote {out} ({out.stat().st_size / 1024:.0f} KB)')


if __name__ == '__main__':
    sys.exit(main())
